//! #router-r7 — OFFLINE PRIORS v1 (ROUTER_PROGRAM §5.5, §10 R7): the compiled
//! COST-MODEL table and its pure reader.
//!
//! # What a prior is here, and what it is not
//!
//! A cost model predicts how long a PHASE takes from static row facts:
//! `log2(seconds) = intercept[cell] + slope * log2(params)`, with an upper
//! quantile `+ spread_k * spread[cell]`. It predicts TIME. It never predicts a
//! verdict, a route, a lane's success or what the row "is": the generalization
//! audit (2026-09-28) refuted static-feature auto-selection because size
//! features fingerprint the corpus (`n_params` alone isolates every scored
//! group), so this module is built to make a lookup-by-identity impossible:
//!
//! * the KEY a model is indexed by is two operator bits ([`CostKey`]: has a
//!   convolution, has a non-piecewise-linear operator) — never a size, a
//!   budget, an input dimension or an operator-signature id;
//! * the continuous size enters through ONE exponent shared by every cell of
//!   a phase (a single monotone map), never as a key ([`PriorTable::validate`]
//!   refuses a table whose cells carry different slopes);
//! * every shipped cell spans at least two family-level leakage groups with
//!   the dominant one carrying at most [`PURITY_MAX`] of its weight, a
//!   classifier on the key cannot recover the group on held-out models beyond
//!   [`FINGERPRINT_EXCESS_MAX`], every phase passed leave-one-family-out
//!   with a bounded overfit gap ([`OVERFIT_GAP_MAX_LOG2`]), and its ship
//!   decision survives the removal of ANY one family (G7). The pipeline
//!   (`scripts/router_priors/`) records those numbers in the table, this
//!   reader refuses a table whose records break them, and
//!   `tests/router_priors.rs` re-derives them from the committed anonymised
//!   training manifest.
//!
//! The classifier bound (G3) is a property of the KEY. The prior's full input
//! (key + size), and so the per-row prediction its view logs, DO identify the
//! family on held-out models — the prediction is a monotone map of the size
//! inside a cell (review, measured on the v1 manifest: 1-NN on the logged
//! `verifier.setup` median beats the majority baseline by ~0.35, above
//! [`FINGERPRINT_EXCESS_MAX`]). What keeps it from being a lookup by identity
//! is CAPACITY — one exponent per phase, at most one intercept per cell of the
//! closed key vocabulary — checked out of family by G6 and G7, not blindness
//! (`priors_outputs_carry_the_size_fingerprint_so_the_guard_is_capacity`).
//!
//! # How the router reads it
//!
//! Only under `optimizer.priors: true` (default `false`) and only on the
//! declared host class the table was measured on: a prior measured on one
//! host says nothing about another (a different class prices nothing). The
//! row's [`PriorView`] then rides in the policy input (hashed, logged,
//! replayed) and the bound capabilities get a FIRST RUNG (setup plus one
//! progress window, §3.2 C6). The plan reads it for CR-C contracts and logs the
//! per-phase predictions; R2's CR-A reads a rung that does not fit the window
//! as "do not govern this slot", which leaves today's deadline in place. So a
//! wrong prediction can only make a lane keep today's cap or log a wrong
//! number — it cannot shorten a lane, move a reserve or touch a bound.
//!
//! # Layer B
//!
//! Success curves (`p_k(cap | bucket)` for the lane-allocation MCKP) fit ONLY
//! on generic-board rows, and none exist: v1 ships them UNIFORM, and the reader
//! refuses a table that claims otherwise ([`LayerB`]).
//!
//! PURE: no clock, no environment, no filesystem, no global. The table is
//! compiled in (`include_str!`), parsed on demand, and its sha256 is part of
//! the version token every plan line and receipt carries.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use super::decl::{OpKind, RuleId};
use super::facts::{HostClass, HostEnvelope, InstanceFacts};

/// The table's record schema.
pub const PRIORS_SCHEMA: &str = "ny-router-priors/v1";

/// The compiled cost-model table (generated by
/// `scripts/router_priors/build_priors.py fit`; never hand-edited — the
/// pipeline's `check` regenerates it from its committed training set).
pub const COST_TABLE_V1: &str = include_str!("priors_v1.tsv");

/// The rule identity the plan logs when the prior is read.
pub const RULE_PRIORS: RuleId = RuleId("rule.priors");

/// G2: a shipped cell spans at least this many family-level leakage groups.
pub const MIN_FAMILIES_PER_CELL: u64 = 2;
/// G2: the dominant group carries at most this share of a cell's weight.
pub const PURITY_MAX: f64 = 0.6;
/// G3: a key classifier may beat the majority baseline by at most this much
/// (family-balanced accuracy, held-out models).
pub const FINGERPRINT_EXCESS_MAX: f64 = 0.20;
/// G5: the shared exponent's admissible range.
pub const SLOPE_MIN: f64 = 0.0;
/// G5: the shared exponent's admissible range.
pub const SLOPE_MAX: f64 = 2.0;
/// G6: the leave-one-family-out overfit gap ceiling, log2 units.
pub const OVERFIT_GAP_MAX_LOG2: f64 = 0.5;
/// The root cell.
pub const ROOT_CELL: &str = "*";
/// The only work variable v1 knows.
pub const WORK_PARAMS: &str = "params";
/// The cells a model may be indexed by (G1). Nothing else is a key.
pub const CELLS: [&str; 5] = [
    ROOT_CELL,
    "conv=0;nonpwl=0",
    "conv=0;nonpwl=1",
    "conv=1;nonpwl=0",
    "conv=1;nonpwl=1",
];
/// The units a model may predict.
pub const UNITS: [&str; 4] = ["secs", "secs_per_clause", "bytes", "units"];
/// A prediction above this is not a planning number (one day, in ms).
pub const PREDICTION_CEILING_MS: u64 = 86_400_000;

/// The coarse operator key (G1): two bits of the operator signature.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct CostKey {
    /// The model has a convolution or a transposed convolution.
    pub conv: bool,
    /// The model has a sigmoid, tanh, softmax, bilinear product or
    /// normalisation layer.
    pub nonpwl: bool,
}

impl CostKey {
    /// The key of a row, or `None` when it cannot be read exactly: unknown
    /// facts, or an incomplete operator signature (the `nonpwl` bit would be
    /// a lower bound). A `None` key reads the root model.
    #[must_use]
    pub fn from_facts(facts: &InstanceFacts) -> Option<Self> {
        if !facts.is_known() || !facts.ops_complete {
            return None;
        }
        let ops = facts.ops;
        Some(Self {
            conv: ops.contains(OpKind::Conv) || ops.contains(OpKind::ConvTranspose),
            nonpwl: [
                OpKind::Sigmoid,
                OpKind::Tanh,
                OpKind::Softmax,
                OpKind::Bilinear,
                OpKind::Norm,
            ]
            .into_iter()
            .any(|kind| ops.contains(kind)),
        })
    }

    /// The cell token (`conv=<0|1>;nonpwl=<0|1>`).
    #[must_use]
    pub fn token(self) -> String {
        format!(
            "conv={};nonpwl={}",
            u8::from(self.conv),
            u8::from(self.nonpwl)
        )
    }
}

/// One phase's cost model in one cell.
#[derive(Debug, Clone, PartialEq)]
pub struct CostModel {
    /// The phase (`attack.upfront`, `verifier.setup`, ...).
    pub phase: String,
    /// What it predicts (`secs`, `secs_per_clause`, ...).
    pub unit: String,
    /// The work variable (`params`).
    pub work: String,
    /// The cell (`*` or a [`CostKey`] token).
    pub cell: String,
    /// log2 intercept.
    pub intercept: f64,
    /// The shared exponent.
    pub slope: f64,
    /// Weighted median |residual|, log2.
    pub spread: f64,
    /// (family, model) units it was fit on.
    pub units: u64,
    /// Family-level leakage groups among them.
    pub families: u64,
    /// The dominant group's share of the cell's weight.
    pub share_max: f64,
}

/// The pipeline's recorded gate evidence for one shipped phase.
#[derive(Debug, Clone, PartialEq)]
pub struct PhaseEvidence {
    /// The phase.
    pub phase: String,
    /// Families held out by LOGO.
    pub logo_families: u64,
    /// Median over held-out families of (held-out − full-fit) error, log2.
    pub gap_median: f64,
    /// Median held-out error, log2.
    pub heldout_median: f64,
    /// Median held-out error of the constant null, log2.
    pub null_median: f64,
    /// Held-out families where the model beat the null.
    pub wins: u64,
    /// Held-out families where the null beat the model.
    pub losses: u64,
    /// Exact two-sided sign-test p of wins vs losses.
    pub sign_p: f64,
    /// Key-classifier family-balanced accuracy on held-out models.
    pub fp_accuracy: f64,
    /// The majority baseline under the same protocol.
    pub fp_baseline: f64,
    /// `fp_accuracy − fp_baseline`.
    pub fp_excess: f64,
    /// Cells containing one family only (G4).
    pub isolating: u64,
    /// G7: leave-one-family-out refits that still pass G2-G6.
    pub stable_folds: u64,
    /// G7: the refits tried (one per family).
    pub stable_of: u64,
}

/// Which phases price which capability's first rung.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Binding {
    /// The capability (registry id).
    pub cap: String,
    /// The phases whose upper predictions sum to its first rung.
    pub phases: Vec<String>,
}

/// Layer-B success curves. v1 is UNIFORM by rule (§5.5): the only admissible
/// training rows are generic-board rows, and none exist.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LayerB {
    /// The Beta(1,1) mean everywhere.
    Uniform {
        /// Why (recorded by the pipeline).
        why: String,
    },
}

/// Why the table could not be read.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PriorError {
    /// A malformed line.
    Parse {
        /// 1-based line number.
        line: usize,
        /// What was wrong.
        what: String,
    },
    /// A well-formed table whose records break a gate.
    Invalid(Vec<String>),
}

impl std::fmt::Display for PriorError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Parse { line, what } => write!(f, "priors table line {line}: {what}"),
            Self::Invalid(violations) => {
                write!(
                    f,
                    "priors table breaks {} gate(s): {}",
                    violations.len(),
                    violations.join("; ")
                )
            }
        }
    }
}

/// The parsed table.
#[derive(Debug, Clone, PartialEq)]
pub struct PriorTable {
    /// [`PRIORS_SCHEMA`].
    pub schema: String,
    /// `cost-v1`.
    pub version: String,
    /// The host class every observation was measured on.
    pub host: HostClass,
    /// sha256 of the training-row manifest the pipeline fit.
    pub trainset_sha256: String,
    /// Receipts that contributed an observation.
    pub receipts: u64,
    /// The upper quantile's spread multiplier.
    pub spread_k: f64,
    /// The spread floor, log2.
    pub spread_floor_log2: f64,
    /// Gate constants as the pipeline recorded them.
    pub gates: Vec<(String, f64)>,
    /// Shipped models.
    pub models: Vec<CostModel>,
    /// Per shipped phase, the gate evidence.
    pub evidence: Vec<PhaseEvidence>,
    /// `(phase, why)` for every phase the gates refused.
    pub refused: Vec<(String, String)>,
    /// First-rung bindings.
    pub bindings: Vec<Binding>,
    /// Layer-B success curves.
    pub layer_b: LayerB,
    /// sha256 of the table text.
    pub digest: [u8; 32],
}

/// One phase's prediction for a row, integer milliseconds.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PhasePrediction {
    /// The phase.
    pub phase: String,
    /// The cell whose model answered (`*` when the row's key has no model).
    pub cell: String,
    /// The median prediction.
    pub median_ms: u64,
    /// The upper prediction (`+ spread_k * spread`).
    pub upper_ms: u64,
}

/// A capability the prior priced.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PricedCap {
    /// The capability.
    pub cap: String,
    /// Its first rung, milliseconds (sum of its phases' upper predictions).
    pub ms: u64,
}

/// A bound capability the prior did not price, and why.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct UnpricedCap {
    /// The capability.
    pub cap: String,
    /// `host:<class>`, `params-unknown`, `<phase>:refused`, ...
    pub reason: String,
}

/// What the prior says about ONE row: the part of the policy input it adds.
/// Integers and tokens only (hashed, serialized and replayed exactly).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PriorView {
    /// [`PriorTable::version_token`].
    pub version: String,
    /// The host class the table was measured on.
    pub host: String,
    /// The row's key token (`None` = unknown key: the root model answers).
    pub cell: Option<String>,
    /// Every modelled phase the row could be priced for.
    pub predictions: Vec<PhasePrediction>,
    /// Bound capabilities the prior priced, binding order.
    pub priced: Vec<PricedCap>,
    /// Bound capabilities it did not, binding order.
    pub unpriced: Vec<UnpricedCap>,
}

impl PriorView {
    /// The first rung the prior priced for `cap`, if any.
    #[must_use]
    pub fn rung_ms(&self, cap: &str) -> Option<u64> {
        self.priced.iter().find(|p| p.cap == cap).map(|p| p.ms)
    }
}

fn parse_f64(text: &str, line: usize, what: &str) -> Result<f64, PriorError> {
    let value: f64 = text.trim().parse().map_err(|_| PriorError::Parse {
        line,
        what: format!("{what}: not a number: {text:?}"),
    })?;
    if value.is_finite() {
        Ok(value)
    } else {
        Err(PriorError::Parse {
            line,
            what: format!("{what}: not finite"),
        })
    }
}

fn parse_u64(text: &str, line: usize, what: &str) -> Result<u64, PriorError> {
    text.trim().parse().map_err(|_| PriorError::Parse {
        line,
        what: format!("{what}: not an unsigned integer: {text:?}"),
    })
}

/// The value of `key=value` among an evidence line's fields.
fn kv<'t>(fields: &[&'t str], key: &str, line: usize) -> Result<&'t str, PriorError> {
    fields
        .iter()
        .find_map(|field| field.strip_prefix(key)?.strip_prefix('='))
        .ok_or_else(|| PriorError::Parse {
            line,
            what: format!("evidence lacks {key}="),
        })
}

impl PriorTable {
    /// Parse a table. Strict: an unknown record kind, a wrong field count or a
    /// non-finite number is an error, never skipped.
    pub fn parse(text: &str) -> Result<Self, PriorError> {
        let mut table = Self {
            schema: String::new(),
            version: String::new(),
            host: HostClass::Other,
            trainset_sha256: String::new(),
            receipts: 0,
            spread_k: f64::NAN,
            spread_floor_log2: f64::NAN,
            gates: Vec::new(),
            models: Vec::new(),
            evidence: Vec::new(),
            refused: Vec::new(),
            bindings: Vec::new(),
            layer_b: LayerB::Uniform { why: String::new() },
            digest: Sha256::digest(text.as_bytes()).into(),
        };
        let mut host_seen = false;
        let mut layer_b_seen = false;
        for (index, raw) in text.lines().enumerate() {
            let line = index + 1;
            if raw.trim().is_empty() || raw.starts_with('#') {
                continue;
            }
            let fields: Vec<&str> = raw.split('\t').collect();
            let want = |n: usize| -> Result<(), PriorError> {
                if fields.len() == n {
                    Ok(())
                } else {
                    Err(PriorError::Parse {
                        line,
                        what: format!("`{}` takes {n} fields, found {}", fields[0], fields.len()),
                    })
                }
            };
            match fields[0] {
                "schema" => {
                    want(2)?;
                    table.schema = fields[1].to_owned();
                }
                "version" => {
                    want(2)?;
                    table.version = fields[1].to_owned();
                }
                "host" => {
                    want(2)?;
                    table.host =
                        HostClass::from_token(fields[1]).ok_or_else(|| PriorError::Parse {
                            line,
                            what: format!("unknown host class {:?}", fields[1]),
                        })?;
                    host_seen = true;
                }
                "trainset_sha256" => {
                    want(2)?;
                    table.trainset_sha256 = fields[1].to_owned();
                }
                "receipts" => {
                    want(2)?;
                    table.receipts = parse_u64(fields[1], line, "receipts")?;
                }
                "spread_k" => {
                    want(2)?;
                    table.spread_k = parse_f64(fields[1], line, "spread_k")?;
                }
                "spread_floor_log2" => {
                    want(2)?;
                    table.spread_floor_log2 = parse_f64(fields[1], line, "spread_floor_log2")?;
                }
                "layer_b" => {
                    want(3)?;
                    if fields[1] != "uniform" {
                        return Err(PriorError::Parse {
                            line,
                            what: format!(
                                "layer_b {:?}: v1 success curves ship UNIFORM (no generic-board rows)",
                                fields[1]
                            ),
                        });
                    }
                    table.layer_b = LayerB::Uniform {
                        why: fields[2].to_owned(),
                    };
                    layer_b_seen = true;
                }
                "gate" => {
                    want(3)?;
                    table
                        .gates
                        .push((fields[1].to_owned(), parse_f64(fields[2], line, fields[1])?));
                }
                "model" => {
                    want(11)?;
                    table.models.push(CostModel {
                        phase: fields[1].to_owned(),
                        unit: fields[2].to_owned(),
                        work: fields[3].to_owned(),
                        cell: fields[4].to_owned(),
                        intercept: parse_f64(fields[5], line, "intercept")?,
                        slope: parse_f64(fields[6], line, "slope")?,
                        spread: parse_f64(fields[7], line, "spread")?,
                        units: parse_u64(fields[8], line, "units")?,
                        families: parse_u64(fields[9], line, "families")?,
                        share_max: parse_f64(fields[10], line, "share_max")?,
                    });
                }
                "evidence" => {
                    want(15)?;
                    let rest = &fields[2..];
                    let get = |key: &str| kv(rest, key, line);
                    table.evidence.push(PhaseEvidence {
                        phase: fields[1].to_owned(),
                        logo_families: parse_u64(get("logo_families")?, line, "logo_families")?,
                        gap_median: parse_f64(get("gap_median")?, line, "gap_median")?,
                        heldout_median: parse_f64(get("heldout_median")?, line, "heldout_median")?,
                        null_median: parse_f64(get("null_median")?, line, "null_median")?,
                        wins: parse_u64(get("wins")?, line, "wins")?,
                        losses: parse_u64(get("losses")?, line, "losses")?,
                        sign_p: parse_f64(get("sign_p")?, line, "sign_p")?,
                        fp_accuracy: parse_f64(get("fp_accuracy")?, line, "fp_accuracy")?,
                        fp_baseline: parse_f64(get("fp_baseline")?, line, "fp_baseline")?,
                        fp_excess: parse_f64(get("fp_excess")?, line, "fp_excess")?,
                        isolating: parse_u64(get("isolating")?, line, "isolating")?,
                        stable_folds: parse_u64(get("stable_folds")?, line, "stable_folds")?,
                        stable_of: parse_u64(get("stable_of")?, line, "stable_of")?,
                    });
                }
                "refused" => {
                    want(3)?;
                    table
                        .refused
                        .push((fields[1].to_owned(), fields[2].to_owned()));
                }
                "bind" => {
                    want(3)?;
                    table.bindings.push(Binding {
                        cap: fields[1].to_owned(),
                        phases: fields[2].split('+').map(str::to_owned).collect(),
                    });
                }
                other => {
                    return Err(PriorError::Parse {
                        line,
                        what: format!("unknown record kind {other:?}"),
                    })
                }
            }
        }
        if !host_seen {
            return Err(PriorError::Parse {
                line: 0,
                what: "no host line: a prior must say which host it was measured on".to_owned(),
            });
        }
        if !layer_b_seen {
            return Err(PriorError::Parse {
                line: 0,
                what: "no layer_b line".to_owned(),
            });
        }
        Ok(table)
    }

    /// The compiled table, parsed and validated. Any parse error or gate
    /// violation is an `Err`: the caller prices NOTHING (today's caps).
    pub fn compiled() -> Result<Self, PriorError> {
        let table = Self::parse(COST_TABLE_V1)?;
        let violations = table.validate();
        if violations.is_empty() {
            Ok(table)
        } else {
            Err(PriorError::Invalid(violations))
        }
    }

    /// `cost-v1+<sha8 of the table text>`.
    #[must_use]
    pub fn version_token(&self) -> String {
        format!("{}+{}", self.version, super::hash::sha8(&self.digest))
    }

    /// The gate constant the pipeline recorded under `name`.
    #[must_use]
    pub fn gate(&self, name: &str) -> Option<f64> {
        self.gates.iter().find(|(n, _)| n == name).map(|(_, v)| *v)
    }

    /// Phases with at least one shipped model, table order.
    #[must_use]
    pub fn shipped_phases(&self) -> Vec<&str> {
        let mut out: Vec<&str> = Vec::new();
        for model in &self.models {
            if !out.contains(&model.phase.as_str()) {
                out.push(model.phase.as_str());
            }
        }
        out
    }

    /// Every structural gate, with ALL violations reported at once.
    #[must_use]
    pub fn validate(&self) -> Vec<String> {
        let mut bad = Vec::new();
        if self.schema != PRIORS_SCHEMA {
            bad.push(format!("schema {:?} is not {PRIORS_SCHEMA}", self.schema));
        }
        if self.version.is_empty() || self.version.contains('+') {
            bad.push(format!("version {:?} must be a bare token", self.version));
        }
        if self.trainset_sha256.len() != 64
            || !self.trainset_sha256.bytes().all(|b| b.is_ascii_hexdigit())
        {
            bad.push("trainset_sha256 is not a sha256".to_owned());
        }
        if !(self.spread_k.is_finite() && self.spread_k >= 0.0) {
            bad.push("spread_k is not a finite non-negative number".to_owned());
        }
        if !(self.spread_floor_log2.is_finite() && self.spread_floor_log2 >= 0.0) {
            bad.push("spread_floor_log2 is not a finite non-negative number".to_owned());
        }
        // The pipeline's gate constants must be THIS reader's.
        for (name, want) in [
            ("min_families_per_cell", MIN_FAMILIES_PER_CELL as f64),
            ("purity_max", PURITY_MAX),
            ("fingerprint_excess_max", FINGERPRINT_EXCESS_MAX),
            ("slope_min", SLOPE_MIN),
            ("slope_max", SLOPE_MAX),
            ("overfit_gap_max_log2", OVERFIT_GAP_MAX_LOG2),
        ] {
            match self.gate(name) {
                Some(got) if (got - want).abs() <= 1e-9 => {}
                Some(got) => bad.push(format!("gate {name}={got} but the reader enforces {want}")),
                None => bad.push(format!("gate {name} is not recorded")),
            }
        }
        for model in &self.models {
            let at = format!("{}[{}]", model.phase, model.cell);
            // G1: the key and the work variable come from a closed vocabulary.
            if !CELLS.contains(&model.cell.as_str()) {
                bad.push(format!(
                    "G1 {at}: cell {:?} is not a coarse operator key",
                    model.cell
                ));
            }
            if model.work != WORK_PARAMS {
                bad.push(format!(
                    "G1 {at}: work {:?} is not {WORK_PARAMS}",
                    model.work
                ));
            }
            if !UNITS.contains(&model.unit.as_str()) {
                bad.push(format!("{at}: unit {:?} is unknown", model.unit));
            }
            // G2: no cell is one group's constant.
            if model.families < MIN_FAMILIES_PER_CELL {
                bad.push(format!(
                    "G2 {at}: spans {} family(ies) < {MIN_FAMILIES_PER_CELL}",
                    model.families
                ));
            }
            if model.cell != ROOT_CELL && model.share_max > PURITY_MAX + 1e-9 {
                bad.push(format!(
                    "G2 {at}: dominant family share {} > {PURITY_MAX}",
                    model.share_max
                ));
            }
            // G5: one monotone exponent.
            if !(SLOPE_MIN..=SLOPE_MAX).contains(&model.slope) {
                bad.push(format!(
                    "G5 {at}: slope {} outside [{SLOPE_MIN}, {SLOPE_MAX}]",
                    model.slope
                ));
            }
            if model.spread + 1e-9 < self.spread_floor_log2 {
                bad.push(format!("{at}: spread {} below the floor", model.spread));
            }
        }
        for phase in self.shipped_phases() {
            let models: Vec<&CostModel> = self.models.iter().filter(|m| m.phase == phase).collect();
            if !models.iter().any(|m| m.cell == ROOT_CELL) {
                bad.push(format!("{phase}: no root model"));
            }
            if models
                .windows(2)
                .any(|w| w[0].slope.to_bits() != w[1].slope.to_bits())
            {
                bad.push(format!(
                    "G5 {phase}: cells carry different slopes (size would become a key)"
                ));
            }
            if models.windows(2).any(|w| w[0].unit != w[1].unit) {
                bad.push(format!("{phase}: cells disagree on the unit"));
            }
            let mut cells: Vec<&str> = models.iter().map(|m| m.cell.as_str()).collect();
            cells.sort_unstable();
            if cells.windows(2).any(|w| w[0] == w[1]) {
                bad.push(format!("{phase}: duplicate cell"));
            }
            if self.refused.iter().any(|(p, _)| p == phase) {
                bad.push(format!("{phase}: both shipped and refused"));
            }
            match self.evidence.iter().find(|e| e.phase == phase) {
                None => bad.push(format!("{phase}: shipped without gate evidence")),
                Some(e) => {
                    if e.fp_excess > FINGERPRINT_EXCESS_MAX + 1e-9 {
                        bad.push(format!(
                            "G3 {phase}: key classifier excess {} > {FINGERPRINT_EXCESS_MAX}",
                            e.fp_excess
                        ));
                    }
                    if (e.fp_accuracy - e.fp_baseline - e.fp_excess).abs() > 1e-5 {
                        bad.push(format!("G3 {phase}: excess != accuracy - baseline"));
                    }
                    if e.isolating != 0 {
                        bad.push(format!("G4 {phase}: {} isolating cell(s)", e.isolating));
                    }
                    if e.gap_median > OVERFIT_GAP_MAX_LOG2 + 1e-9 {
                        bad.push(format!(
                            "G6 {phase}: LOGO overfit gap {} > {OVERFIT_GAP_MAX_LOG2}",
                            e.gap_median
                        ));
                    }
                    if e.losses > e.wins {
                        bad.push(format!(
                            "G6 {phase}: LOGO loses to the constant null ({}W/{}L)",
                            e.wins, e.losses
                        ));
                    }
                    if e.logo_families < MIN_FAMILIES_PER_CELL {
                        bad.push(format!("G6 {phase}: {} held-out families", e.logo_families));
                    }
                    if e.stable_of < MIN_FAMILIES_PER_CELL || e.stable_folds != e.stable_of {
                        bad.push(format!(
                            "G7 {phase}: ship decision holds in {} of {} leave-one-family-out refits",
                            e.stable_folds, e.stable_of
                        ));
                    }
                }
            }
        }
        for e in &self.evidence {
            if !self.shipped_phases().contains(&e.phase.as_str()) {
                bad.push(format!(
                    "{}: evidence for a phase that ships no model",
                    e.phase
                ));
            }
        }
        for binding in &self.bindings {
            if binding.phases.is_empty() {
                bad.push(format!("bind {}: no phase", binding.cap));
            }
            for phase in &binding.phases {
                let shipped = self.models.iter().any(|m| &m.phase == phase);
                let refused = self.refused.iter().any(|(p, _)| p == phase);
                if !shipped && !refused {
                    bad.push(format!(
                        "bind {}: phase {phase} is neither shipped nor refused",
                        binding.cap
                    ));
                }
            }
        }
        bad
    }

    /// The model answering `phase` for a row whose key is `key`: the key's
    /// cell when the table ships one, else the root.
    fn model_for(&self, phase: &str, key: Option<CostKey>) -> Option<&CostModel> {
        let cell = key.map(CostKey::token);
        cell.as_deref()
            .and_then(|cell| {
                self.models
                    .iter()
                    .find(|m| m.phase == phase && m.cell == cell)
            })
            .or_else(|| {
                self.models
                    .iter()
                    .find(|m| m.phase == phase && m.cell == ROOT_CELL)
            })
    }

    /// Predict `phase` for a row. `Err` says why it is unpriced.
    pub fn predict(
        &self,
        phase: &str,
        facts: &InstanceFacts,
        host: &HostEnvelope,
    ) -> Result<PhasePrediction, String> {
        if host.class != self.host {
            return Err(format!("host:{}", host.class.token()));
        }
        if self.refused.iter().any(|(p, _)| p == phase) {
            return Err(format!("{phase}:refused"));
        }
        if !facts.is_known() {
            return Err("facts-unknown".to_owned());
        }
        let params = match facts.params {
            Some(params) if params > 0 => params,
            _ => return Err("params-unknown".to_owned()),
        };
        let key = CostKey::from_facts(facts);
        let model = self
            .model_for(phase, key)
            .ok_or_else(|| format!("{phase}:unmodelled"))?;
        let scale = match model.unit.as_str() {
            "secs" => 1.0,
            "secs_per_clause" => match facts.clauses {
                Some(clauses) if clauses > 0 => clauses as f64,
                _ => return Err(format!("{phase}:clauses-unknown")),
            },
            other => return Err(format!("{phase}:unit-{other}-is-not-time")),
        };
        let x = (params as f64).log2();
        let median_log2 = model.intercept + model.slope * x;
        let upper_log2 = median_log2 + self.spread_k * model.spread;
        let median_ms = to_ms(median_log2, scale).ok_or_else(|| format!("{phase}:non-finite"))?;
        let upper_ms = to_ms(upper_log2, scale).ok_or_else(|| format!("{phase}:non-finite"))?;
        Ok(PhasePrediction {
            phase: phase.to_owned(),
            cell: model.cell.clone(),
            median_ms,
            upper_ms: upper_ms.max(median_ms),
        })
    }

    /// The first rung of `cap`: the sum of its bound phases' UPPER predictions
    /// (saturating). `Err` says why it is unpriced.
    pub fn first_rung_ms(
        &self,
        cap: &str,
        facts: &InstanceFacts,
        host: &HostEnvelope,
    ) -> Result<u64, String> {
        let binding = self
            .bindings
            .iter()
            .find(|b| b.cap == cap)
            .ok_or_else(|| "unbound".to_owned())?;
        let mut total: u64 = 0;
        for phase in &binding.phases {
            total = total.saturating_add(self.predict(phase, facts, host)?.upper_ms);
        }
        Ok(total.min(PREDICTION_CEILING_MS))
    }

    /// What the prior says about one row.
    #[must_use]
    pub fn view(&self, facts: &InstanceFacts, host: &HostEnvelope) -> PriorView {
        let predictions = self
            .shipped_phases()
            .into_iter()
            .filter_map(|phase| self.predict(phase, facts, host).ok())
            .collect();
        let mut priced = Vec::new();
        let mut unpriced = Vec::new();
        for binding in &self.bindings {
            match self.first_rung_ms(&binding.cap, facts, host) {
                Ok(ms) => priced.push(PricedCap {
                    cap: binding.cap.clone(),
                    ms,
                }),
                Err(reason) => unpriced.push(UnpricedCap {
                    cap: binding.cap.clone(),
                    reason,
                }),
            }
        }
        PriorView {
            version: self.version_token(),
            host: self.host.token().to_owned(),
            cell: CostKey::from_facts(facts).map(CostKey::token),
            predictions,
            priced,
            unpriced,
        }
    }
}

/// `2^log2 * scale` seconds as whole milliseconds (ceil), inside
/// `[1, PREDICTION_CEILING_MS]`; `None` when not finite.
fn to_ms(log2_secs: f64, scale: f64) -> Option<u64> {
    let ms = log2_secs.exp2() * scale * 1000.0;
    if !ms.is_finite() || ms < 0.0 {
        return None;
    }
    let ceiled = ms.ceil();
    if ceiled >= PREDICTION_CEILING_MS as f64 {
        Some(PREDICTION_CEILING_MS)
    } else {
        // In [0, ceiling): the conversion is exact for every integer here.
        Some((ceiled as u64).max(1))
    }
}
