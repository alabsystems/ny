//! S1 `special` — eight declared points, no search.
//!
//! # The evidence
//!
//! `reports/falsification_audit/selftest_calibration.json`, 60 s budget, 100
//! rows known to be SAT: **34 of the 75 refutations were won by `special`** —
//! 45% of the rows for 2% of the plan's budget, the best value in the table by
//! an order of magnitude. On every one of those 34 rows the effort record reads
//! `"strategies_run": {"special": 8}` and the wall clock reads **0.016-0.686 s**.
//! It won `collins_rul` 5/5, `tllverifybench` 5/5, `cgan` 5/5, `sat_relu` 4,
//! `ml4acopf` 3, `dist_shift` 3, and six more families.
//!
//! # Why ny does not already have this
//!
//! ny's nearest lane is `low_dim_ort_corner_falsify` (`vnncomp.rs:11468`),
//! which enumerates `low_dim_corner_seeds` — *box vertices only*, and only when
//! the free-dimension count is at most `UPFRONT_CORNER_MAX_VARIABLE_DIMS = 5`;
//! above that it returns an empty vector and the lane is a no-op.
//!
//! Both halves of that matter:
//!
//! - **Four of the eight patterns are not vertices.** The centre, and the two
//!   bound/centre midpoints, are interior; the parity patterns are vertices but
//!   are the specific two that a `0..2^d` enumeration reaches last.
//! - **`special` has no dimension cap.** It won `collins_rul`
//!   `if_then_7levels_w20` at **200 free inputs**, where corner enumeration is
//!   `2^200` and ny's lane refuses outright. Eight points is eight points at
//!   any dimension.
//!
//! # Port fidelity
//!
//! The pattern list, its order, and the float32 snapping are ported exactly
//! from `Searcher._strategy_special`. `tests/calibration_special.rs` pins the
//! emitted matrix against a golden fixture generated by running that Python
//! function itself, so a drifting port fails the build rather than quietly
//! searching somewhere else.

use crate::admission::{
    Admission, AdmissionContext, AdmissionProfile, AdmissionStage, Arming, CostClass, Decline,
    ObjectiveRequirement, ParamSpace, SpecShape,
};
use crate::domain::SearchBox;
use crate::oracle::Oracle;
use crate::proposal::{Effort, Proposal, StrategyName};
use crate::registry::{Budget, SearchState};
use crate::stall::{StallRule, WorkUnit};

/// `special`'s own free-dimension ceiling.
///
/// PER STRATEGY, NEVER SHARED (design §5 rule 3). It is enormous compared with
/// [`super::SQUARE_MAX_FREE_DIMS`] and that is correct, not sloppy: the cost of
/// this strategy is eight points regardless of dimension, so the only thing the
/// ceiling guards is the memory of building eight vectors. Sharing a ceiling
/// between two strategies over the same fragment is a *measured* regression —
/// letting the LP lane inherit the STE lane's 32768 free-unit cap took
/// `model_30_idx_1703_eps_15` from 1.3 s to 139.4 s for 0 accepted flips.
pub const SPECIAL_MAX_FREE_DIMS: usize = 1 << 22;

/// The eight declared patterns, in emission order. Named so a receipt can say
/// which one hit, and so the port-fidelity test can assert the order.
pub const SPECIAL_PATTERNS: [&str; 8] = [
    "all_low",
    "all_high",
    "centre",
    "parity_even_low",
    "parity_even_high",
    "every_third_high",
    "low_centre_midpoint",
    "high_centre_midpoint",
];

/// S1.
#[derive(Debug, Clone, Copy, Default)]
pub struct SpecialPoints;

impl SpecialPoints {
    /// Build the eight patterns in free coordinates, in emission order.
    ///
    /// Exactly `Searcher._strategy_special`'s `patterns` list.
    pub fn patterns(domain: &SearchBox) -> Vec<Vec<f64>> {
        let n = domain.free_dims();
        if n == 0 {
            // The Python evaluates one zero-width row here: a fully pinned spec
            // still has exactly one point in it, and cctsdb-style
            // equality-pinned specs are falsifiable precisely because that
            // point is checked.
            return vec![Vec::new()];
        }
        let lo = domain.free_lo();
        let hi = domain.free_hi();
        let centre = domain.centre_free();

        let mut patterns = Vec::with_capacity(8);
        patterns.push(lo.to_vec());
        patterns.push(hi.to_vec());
        patterns.push(centre.to_vec());
        patterns.push(
            (0..n)
                .map(|i| if i % 2 == 0 { lo[i] } else { hi[i] })
                .collect(),
        );
        patterns.push(
            (0..n)
                .map(|i| if i % 2 == 0 { hi[i] } else { lo[i] })
                .collect(),
        );
        patterns.push(
            (0..n)
                .map(|i| if i % 3 == 0 { hi[i] } else { lo[i] })
                .collect(),
        );
        patterns.push((0..n).map(|i| lo[i].midpoint(centre[i])).collect());
        patterns.push((0..n).map(|i| hi[i].midpoint(centre[i])).collect());
        patterns
    }
}

impl crate::registry::Strategy for SpecialPoints {
    fn name(&self) -> StrategyName {
        StrategyName::SpecialPoints
    }

    /// `SpecShape`. It never looks at the graph and never loads the model,
    /// which is why its refusal is free.
    fn deepest_stage(&self) -> AdmissionStage {
        AdmissionStage::SpecShape
    }

    /// `DEFAULT_PLAN`'s `("special", 0.02)`.
    fn plan_share(&self) -> f64 {
        0.02
    }

    fn stall_rule(&self) -> StallRule {
        // Vestigial by construction: the strategy emits one logical batch and
        // exits. It is here because the trait requires every strategy to name
        // its own work unit, and "this one cannot stall" is a claim worth
        // making explicitly rather than by omission.
        StallRule::new(WorkUnit::BatchesWithoutNewBest, 1)
    }

    fn admit(&self, ctx: &AdmissionContext<'_>) -> Admission {
        if ctx.arming() == Arming::Dark {
            return Admission::Declined(Decline::Disarmed);
        }
        let spec = ctx.spec();
        if let SpecShape::NonBoxInputAssertions { .. } = spec.shape {
            return Admission::Declined(Decline::SpecShapeUnsupported {
                want: SpecShape::BoxInputs,
                got: spec.shape,
            });
        }
        if spec.free_dims > SPECIAL_MAX_FREE_DIMS {
            return Admission::Declined(Decline::FreeDimsAboveCeiling {
                free: spec.free_dims,
                ceiling: SPECIAL_MAX_FREE_DIMS,
            });
        }
        Admission::Admitted(AdmissionProfile {
            // Value-only: it compares eight numbers. A flat objective does not
            // blind it, which is why it is scheduled first on every row.
            objective: ObjectiveRequirement::ValueOnly,
            needs_incumbent: false,
            needs_verifier_state: false,
            free_dims: spec.free_dims,
            declared_cost: CostClass::Instant,
            params: ParamSpace {
                free_dims_ceiling: SPECIAL_MAX_FREE_DIMS,
                max_points: SPECIAL_PATTERNS.len(),
                max_restarts: 1,
            },
        })
    }

    fn search(
        &mut self,
        domain: &SearchBox,
        oracle: &mut dyn Oracle,
        budget: &Budget,
        state: &mut SearchState,
    ) -> Proposal {
        let started = std::time::Instant::now();
        let mut effort = Effort::default();
        let patterns = Self::patterns(domain);

        for chunk in patterns.chunks(budget.batch.max(1)) {
            if budget.expired() {
                break;
            }
            match super::evaluate(
                domain,
                oracle,
                state,
                &mut effort,
                StrategyName::SpecialPoints,
                chunk,
            ) {
                super::Batch::Hit(candidate) => {
                    let mut candidate = *candidate;
                    let mut hit_effort = effort.clone();
                    hit_effort.wall = started.elapsed();
                    candidate = crate::proposal::Candidate::new(
                        candidate.inputs().to_vec(),
                        StrategyName::SpecialPoints,
                        hit_effort,
                    );
                    return Proposal::Candidate(candidate);
                }
                super::Batch::Margins(_) => {}
                super::Batch::OracleFailed => break,
            }
        }

        effort.wall = started.elapsed();
        Proposal::Exhausted(effort)
    }
}
